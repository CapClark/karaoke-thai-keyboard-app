"""Builds web/names.js: common proper nouns with the spellings people type.

Sources:
  tools/names_hand.txt   nicknames, given names, places, brands (hand-written spellings)
  tools/loanwords_hand.txt  English loanwords as Thais write them (keyboard -> คีย์บอร์ด)
  PyThaiNLP provinces()  all 77 provinces
  PyThaiNLP countries()  country names
  PyThaiNLP first names and surnames, but only those that actually appear in the corpora
  (formal TNC or the casual online counts) — thousands of rare names would only add noise.

Output: window.THAI_NAMES = [[thai, "spelling|spelling", rank, "english|spellings"], ...]
The last field lists the hand-written spellings: typed letter for letter, they rank the word
above Thai words that only share its sounds (ken -> เคน before เกณฑ์).
A name that is already a word keeps its own rank and only gains the spellings; `rank` is
used for names the word list lacks (kept modest so names never outrank everyday words).
Usage: .venv/bin/python proper_nouns.py
"""
import json
import os
import re
import warnings

warnings.filterwarnings("ignore")
from pythainlp.corpus import countries, provinces, thai_family_names, thai_female_names, thai_male_names, tnc
from pythainlp.transliterate import romanize

HERE = os.path.dirname(os.path.abspath(__file__))
THAI = re.compile(r"^[฀-๿]+$")
ROM = re.compile(r"^[a-z]+$")

cache_path = os.path.join(HERE, "rom_cache.json")
cache = json.load(open(cache_path, encoding="utf-8")) if os.path.exists(cache_path) else {}
new_roms = 0


def neural(w):
    global new_roms
    if w not in cache:
        try:
            cache[w] = re.sub(r"[^a-z]", "", romanize(w, engine="thai2rom_onnx").lower())
        except Exception:
            cache[w] = ""
        new_roms += 1
    return cache[w]


names = {}  # thai -> [spellings (ordered, unique), rank, hand-written spellings]


def add(w, roms, rank):
    if not THAI.match(w):
        return
    e = names.setdefault(w, [[], rank, []])
    e[1] = max(e[1], rank)
    for r in roms:
        if r and ROM.match(r) and 2 <= len(r) <= 40:
            if r not in e[0]:
                e[0].append(r)


# 1. Hand-written. A spelling listed for two Thai words (แชท / แชต) only marks the first.
taken = set()
for fname in ("names_hand.txt", "loanwords_hand.txt"):
    for line in open(os.path.join(HERE, fname), encoding="utf-8"):
        line = line.split("#")[0].split()
        if len(line) >= 2:
            add(line[0], line[1:], 800)
            if line[0] in names:
                mine = names[line[0]][2]
                for r in line[1:]:
                    if r in names[line[0]][0] and r not in taken and r not in mine:
                        mine.append(r)
                        taken.add(r)
hand = len(names)

# 2. Provinces and countries.
for w in provinces():
    add(w, [neural(w)], 600)
for w in countries():
    if len(w) <= 14:
        add(w, [neural(w)], 400)

# 3. First names and surnames seen in the corpora.
formal = {w: f for w, f in tnc.word_freqs()}
casual_path = os.path.join(HERE, "casual_freq.json")
casual = json.load(open(casual_path, encoding="utf-8")) if os.path.exists(casual_path) else {}
seen = 0
for group in (thai_male_names(), thai_female_names(), thai_family_names()):
    for w in group:
        count = max(formal.get(w, 0), casual.get(w, 0) / 5)
        if count >= 2 and len(w) >= 3 and w not in names:
            add(w, [neural(w)], int(min(300, max(40, count))))
            seen += 1

if new_roms:
    json.dump(cache, open(cache_path, "w", encoding="utf-8"), ensure_ascii=False)
# English spellings that are no Thai word's spelling (josh, keyboard) are marked "!": typed, they can
# only mean that word. The rest (ken, also how เกณฑ์ is spelt) get a smaller bonus.
# Letters Thai romanization (formal or chat) practically never uses: "mee" (มี) is Thai-looking, "josh" isn't.
ENGLISH_ONLY = re.compile(r"c(?!h)|q|x|z|v|sh$|th$|ck|gh|wr|kn|([b-df-hj-np-tv-z])\1|[aeiou][b-df-hj-np-tv-z]e$|[b-df-hj-np-tv-z]y$|y[b-df-hj-np-tv-z]|[aeiou]h[b-df-hj-np-tv-z]")
thai_spellings = set()
src = open(os.path.join(HERE, "..", "web", "dict.js"), encoding="utf-8").read()
d = json.loads(src[src.index("=") + 1:src.rindex(";")])
for rs in d["r"]:
    thai_spellings.update(rs.split("|"))
for p in d.get("p", []):
    thai_spellings.add(p[1])
extra = open(os.path.join(HERE, "..", "web", "extra.js"), encoding="utf-8").read()
thai_spellings.update(re.findall(r'\["[^"]+",\s*"([a-z]+)"\]', extra))
for w, (r, f, h) in names.items():
    thai_spellings.update(x for x in r if x not in h)
out = []
for w, (r, f, h) in names.items():
    if not r:
        continue
    en = "|".join("!" + x if x not in thai_spellings and ENGLISH_ONLY.search(x) else x for x in h)
    out.append([w, "|".join(r), f, en] if en else [w, "|".join(r), f])
strong = sum(x.count("!") for *_, x in [e for e in out if len(e) == 4])
path = os.path.join(HERE, "..", "web", "names.js")
with open(path, "w", encoding="utf-8") as fh:
    fh.write("// Generated by tools/proper_nouns.py from tools/names_hand.txt, tools/loanwords_hand.txt\n")
    fh.write("// and PyThaiNLP name lists. Edit those text files, not this one.\n")
    fh.write("window.THAI_NAMES=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{len(out)} proper nouns -> web/names.js ({hand} hand-written, {seen} corpus names, {new_roms} newly romanized, "
      f"{strong} English-only spellings)")
